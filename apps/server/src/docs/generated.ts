import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import type { Db } from '../db/index.js';
import { openDatabase } from '../db/index.js';
import { withDocsApp } from './export.js';

/** Repository root, three levels above apps/server/src/docs. */
const REPO_ROOT = path.resolve(import.meta.dirname, '..', '..', '..', '..');
export const OPENAPI_FILE = path.join(REPO_ROOT, 'docs', 'openapi.json');
export const SCHEMA_FILE = path.join(REPO_ROOT, 'docs', 'schema.sql');
export const DATABASE_DOC = path.join(REPO_ROOT, 'docs', 'database.md');

const lf = (text: string): string => text.replace(/\r\n/g, '\n');

export async function renderOpenApi(): Promise<string> {
  const spec = await withDocsApp(async (app) => app.swagger());
  return `${JSON.stringify(spec, null, 2)}\n`;
}

interface SchemaRow {
  type: string;
  name: string;
  sql: string;
}

/** Tables first, then indexes, each sorted by name, so the file only changes when the schema does. */
export function renderSchema(db: Db): string {
  const { user_version: version } = db.prepare('PRAGMA user_version').get() as { user_version: number };
  const rows = db
    .prepare(
      `SELECT type, name, sql FROM sqlite_master
       WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%'
       ORDER BY CASE type WHEN 'table' THEN 0 ELSE 1 END, name`,
    )
    .all() as unknown as SchemaRow[];
  const header = [
    '-- Generated by `pnpm db:schema` from apps/server/src/db/migrations.ts. Do not edit.',
    `-- user_version: ${version}`,
  ].join('\n');
  // The migrations indent their SQL by six spaces inside template strings; remove that so the file reads as plain SQL.
  const statement = (sql: string): string => `${lf(sql).replace(/\n {6}/g, '\n')};`;
  return `${header}\n\n${rows.map((row) => statement(row.sql)).join('\n\n')}\n`;
}

export function renderSchemaFromMigrations(): string {
  const db = openDatabase(':memory:');
  try {
    return renderSchema(db);
  } finally {
    db.close();
  }
}

export function tablesIn(schemaSql: string): string[] {
  return [...schemaSql.matchAll(/^CREATE TABLE "?(\w+)"?/gm)].map((match) => match[1] as string);
}

/** Tables with no `### \`name\`` section in docs/database.md. */
export function undocumentedTables(schemaSql: string, databaseDoc: string): string[] {
  return tablesIn(schemaSql).filter((table) => !databaseDoc.includes(`### \`${table}\``));
}

export function writeGenerated(file: string, content: string): void {
  writeFileSync(file, content);
  console.log(`[docs] wrote ${path.relative(REPO_ROOT, file)}`);
}

/** True when the committed file matches `content`; prints the fix otherwise. */
export function matchesCommitted(file: string, content: string, command: string): boolean {
  const relative = path.relative(REPO_ROOT, file);
  if (!existsSync(file)) {
    console.error(`[docs] ${relative} is missing. Run \`${command}\` and commit it.`);
    return false;
  }
  if (lf(readFileSync(file, 'utf8')) === lf(content)) {
    console.log(`[docs] ${relative} is up to date`);
    return true;
  }
  console.error(`[docs] ${relative} is out of date. Run \`${command}\` and commit the result.`);
  return false;
}
